def _read_csv(path: Path) -> list[dict[str, str]]:
    with path.open("r", encoding="utf-8-sig", newline="") as handle:
        return list(csv.DictReader(handle))


@lru_cache(maxsize=1)
def population_profiles() -> dict[str, PopulationProfile]:
    result: dict[str, PopulationProfile] = {}
    for row in _read_csv(PROFILES_CSV):
        shares = tuple(float(row[key]) for key in POP_TYPES)
        result[row["profile"]] = PopulationProfile(
            key=row["profile"],
            shares=shares,
            note=row["note"],
        )
    return result


@lru_cache(maxsize=1)
def realm_census() -> dict[str, RealmCensus]:
    result: dict[str, RealmCensus] = {}
    for row in _read_csv(CENSUS_CSV):
        tag = row["tag"]
        result[tag] = RealmCensus(
            tag=tag,
            total_units=round(float(row["total_k"]) * 1000),
            profile=row["profile"],
            minority_culture=row["minority_culture"],
            minority_faith=row["minority_faith"],
            minority_units=round(float(row["minority_k"] or 0) * 1000),
            minority_location=row["minority_location"],
            minority_type=row["minority_type"],
            source=row["source"],
            note=row["note"],
        )
    return result


