def _census_ledger_payload(state: M5State) -> str:
    political = build_state()
    people = assignments()
    output = io.StringIO(newline="")
    writer = csv.DictWriter(
        output,
        fieldnames=(
            "location",
            "name",
            "region",
            "realm",
            "rank",
            "population_k",
            "culture",
            "faith",
            "minorities",
            "raw_material",
            "engine_rank",
            "abi_cultures",
        ),
        lineterminator="\n",
    )
    writer.writeheader()
    for location in political.model.locations:
        if location.kind != "land":
            continue
        person = people[location.key]
        census = state.locations.get(location.key)
        minorities = ""
        if census:
            minorities = "|".join(
                f"{entry.culture}:{_format_units(entry.units)}"
                for entry in census.entries
                if not entry.technical_abi and entry.culture != person.culture
            )
        settlement = state.settlements.get(location.key)
        writer.writerow(
            {
                "location": location.key,
                "name": political.names[location.key],
                "region": location.region,
                "realm": political.ownership[location.key],
                "rank": political.rank[location.key],
                "population_k": (
                    _format_units(census.custom_units) if census else "0"
                ),
                "culture": person.culture,
                "faith": person.faith,
                "minorities": minorities,
                "raw_material": state.raw_materials[location.key],
                "engine_rank": settlement[0] if settlement else "rural_settlement",
                "abi_cultures": "|".join(
                    state.abi_cultures.get(location.key, ())
                ),
            }
        )
    return output.getvalue()


def _source_sha256() -> str:
    digest = hashlib.sha256()
    for path in (
        PROFILES_CSV,
        CENSUS_CSV,
        MARKETS_CSV,
        ROUTES_CSV,
        SETTLEMENTS_CSV,
        ROOT / "docs/world/census_notes.md",
    ):
        digest.update(path.relative_to(ROOT).as_posix().encode("utf-8"))
        digest.update(path.read_bytes())
    return digest.hexdigest()


def _manifest(state: M5State) -> dict[str, object]:
    targets = realm_census()
    type_units: Counter[str] = Counter()
    culture_units: Counter[str] = Counter()
    faith_units: Counter[str] = Counter()
    for location in state.locations.values():
        for entry in location.entries:
            if entry.technical_abi:
                continue
            type_units[entry.pop_type] += entry.units
            culture_units[entry.culture] += entry.units
            faith_units[entry.faith] += entry.units
    raw_counts = Counter(state.raw_materials.values())
    political = build_state()
    return {
        "milestone": "M5",
        "authored_population_k": round(
            sum(target.total_units for target in targets.values()) / 1000,
            3,
        ),
        "technical_abi_population_k": round(
            len(_installed_cultures()) * 0.01,
            3,
        ),
        "populated_locations": len(state.locations),
        "empty_ruins": sum(
            location.kind == "land"
            and political.rank[location.key] == "ruin"
            for location in political.model.locations
        ),
        "realm_targets_k": {
            key: target.total_units / 1000
            for key, target in sorted(targets.items())
        },
        "population_types_k": {
            key: round(value / 1000, 3)
            for key, value in sorted(type_units.items())
        },
        "culture_population_k": {
            key: round(value / 1000, 3)
            for key, value in sorted(culture_units.items())
        },
        "faith_population_k": {
            key: round(value / 1000, 3)
            for key, value in sorted(faith_units.items())
        },
        "markets": len(markets()),
        "urban_locations": len(state.settlements),
        "authored_route_edges": len(state.route_edges),
        "runtime_road_edges": 0,
        "route_edge_counts": state.route_edge_counts,
        "starting_armies": len(political.realms),
        "raw_material_counts": dict(sorted(raw_counts.items())),
        "source_sha256": _source_sha256(),
    }


def direct_payloads() -> dict[Path, str]:
    state = build_m5_state()
    payloads = {
        TOWN_SETUPS_OUT: _town_setup_payload(),
        DERIVED_CENSUS: _census_ledger_payload(state),
        MANIFEST_OUT: json.dumps(
            _manifest(state),
            indent=2,
            ensure_ascii=False,
        )
        + "\n",
    }
    payloads.update(
        {
            path: _pop_localization_payload(language)
            for language, path in POP_LOC_OUTS.items()
        }
    )
    return payloads


def write() -> None:
    for path, payload in direct_payloads().items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(
            payload,
            encoding=(
                "utf-8-sig"
                if path in {*POP_LOC_OUTS.values(), TOWN_SETUPS_OUT}
                else "utf-8"
            ),
        )
    if ROAD_TYPES_OUT.is_file():
        ROAD_TYPES_OUT.unlink()
    from m2_runtime import start_payloads

    runtime = start_payloads()
    for name in START_NAMES:
        path = START_OUT / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(runtime[path], encoding="utf-8")
    state = build_m5_state()
    print(
        "m5_census: wrote "
        f"{len(state.locations):,} populated locations, "
        f"{len(state.route_edges):,} authored route edges "
        f"(runtime deferred), and {len(markets())} markets"
    )


def _installed_building_keys() -> set[str]:
    result: set[str] = set()
    for root in (
        game_map().parent / "common/building_types",
        ROOT / "in_game/common/building_types",
    ):
        if not root.is_dir():
            continue
        for path in root.glob("*.txt"):
            result.update(
                re.findall(
                    r"(?m)^([A-Za-z0-9_]+)\s*=\s*\{",
                    path.read_text(encoding="utf-8-sig"),
                )
            )
    return result


def check() -> list[str]:
    failures: list[str] = []
    try:
        state = build_m5_state()
    except Exception as exc:
        return [f"could not build M5 state: {exc}"]

    for path, expected in direct_payloads().items():
        if not path.is_file():
            failures.append(f"missing {path.relative_to(ROOT)}")
        elif path.read_text(
            encoding=(
                "utf-8-sig"
                if path in {*POP_LOC_OUTS.values(), TOWN_SETUPS_OUT}
                else "utf-8"
            )
        ) != expected:
            failures.append(f"{path.relative_to(ROOT)} differs from M5 model")
    if ROAD_TYPES_OUT.exists():
        failures.append(
            "stale M5 road-type experiment survives; installed road ABI must remain"
        )

    from m2_runtime import start_payloads

    runtime = start_payloads()
    for name in START_NAMES:
        path = START_OUT / name
        if not path.is_file():
            failures.append(f"missing {path.relative_to(ROOT)}")
        elif path.read_text(encoding="utf-8") != runtime[path]:
            failures.append(f"{path.relative_to(ROOT)} differs from M5 runtime")

    profiles = population_profiles()
    for profile in profiles.values():
        if abs(sum(profile.shares) - 1.0) > 1e-9:
            failures.append(f"profile {profile.key} shares do not sum to one")
    targets = realm_census()
    political = build_state()
    expected_tags = {realm.tag for realm in political.realms} | {WILD}
    if set(targets) != expected_tags:
        failures.append("realm census is not bijective with 38 realms plus WILD")

    realm_units: Counter[str] = Counter()
    custom_cultures: set[str] = set()
    custom_faiths: set[str] = set()
    abi_entries = 0
    for key, location in state.locations.items():
        if len(location.entries) > MAX_SETUP_POP_ENTRIES:
            failures.append(
                f"{key} exceeds the installed "
                f"{MAX_SETUP_POP_ENTRIES}-pop setup contract"
            )
        if state.abi_cultures.get(key) and (
            location.custom_units < MIN_ABI_HOST_UNITS
        ):
            failures.append(
                f"{key} hosts installed culture ABI below "
                f"{MIN_ABI_HOST_UNITS / 1000:.1f}k custom population"
            )
        realm_units[location.realm] += location.custom_units
        custom_total = 0
        for entry in location.entries:
            if entry.technical_abi:
                abi_entries += 1
            else:
                custom_total += entry.units
                custom_cultures.add(entry.culture)
                custom_faiths.add(entry.faith)
        if custom_total != location.custom_units:
            failures.append(f"{key} custom pop split does not match location total")
        if state.abi_cultures.get(key) and location.custom_units <= 10:
            failures.append(f"{key} custom culture does not dominate ABI presence")
    for tag, target in targets.items():
        if realm_units[tag] != target.total_units:
            failures.append(
                f"{tag} census is {_format_units(realm_units[tag])}, "
                f"expected {_format_units(target.total_units)}"
            )
    if custom_cultures != {row.key for row in cultures()}:
        failures.append("custom census does not cover all 33 M4 cultures")
    if custom_faiths != {row.key for row in faiths()}:
        failures.append("custom census does not cover all 10 M4 faiths")
    if abi_entries != len(_installed_cultures()):
        failures.append("installed culture ABI census is incomplete")

    ruin_keys = {
        location.key
        for location in political.model.locations
        if location.kind == "land" and political.rank[location.key] == "ruin"
    }
    if ruin_keys & set(state.locations):
        failures.append("one or more canonical ruins has a starting population")
    land_keys = {
        location.key
        for location in political.model.locations
        if location.kind == "land"
    }
    if set(state.raw_materials) != land_keys:
        failures.append("raw-material map is not bijective with passable land")
    invalid_goods = set(state.raw_materials.values()) - RAW_GOODS
    if invalid_goods:
        failures.append("invalid M5 raw goods: " + ", ".join(sorted(invalid_goods)))
    invalid_lumber = [
        location.key
        for location in political.model.locations
        if state.raw_materials.get(location.key) == "lumber"
    ]
    if invalid_lumber:
        failures.append(
            "lumber assigned while all playable location templates are neutral: "
            + ", ".join(invalid_lumber[:20])
        )

    market_keys = {_resolve_location(market.location) for market in markets()}
    if len(market_keys) != len(markets()):
        failures.append("duplicate market location")
    if not market_keys <= set(state.settlements):
        failures.append("one or more market hubs lacks an urban settlement")
    wild_settlements = sorted(
        key
        for key in state.settlements
        if political.ownership.get(key, WILD) == WILD
    )
    if wild_settlements:
        failures.append(
            "urban setup assigned to deliberately wild land: "
            + ", ".join(wild_settlements[:20])
        )

    graph = _land_graph()
    by_key = political.model.by_key
    for first, second in state.route_edges:
        if by_key[second].index not in graph.get(by_key[first].index, ()):
            failures.append(f"nonadjacent road edge {first} = {second}")
            break
    if not state.route_edges:
        failures.append("authored route ledger is empty")
    if re.search(r"(?m)^\t[A-Za-z0-9_]+\s*=", _roads_payload()):
        failures.append("runtime road graph is not deferred")

    setup_text = _town_setup_payload()
    building_keys = set(
        re.findall(r"(?m)^\t([A-Za-z0-9_]+)\s*=", setup_text)
    )
    missing_buildings = building_keys - _installed_building_keys()
    if missing_buildings:
        failures.append(
            "town setups use missing buildings: "
            + ", ".join(sorted(missing_buildings))
        )
    if len(political.realms) != _armies_payload().count("\tarmy = {"):
        failures.append("starting armies are not bijective with the realm roster")

    generated = "\n".join(runtime_payloads().values()).lower()
    banned = re.findall(
        r"\b(?:cannon|firearm|musket|railroad|cathedral|university|church)\b",
        generated,
    )
    if banned:
        failures.append("anachronistic M5 generated terms: " + ", ".join(banned))
    return failures


def main() -> int:
    parser = argparse.ArgumentParser()
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if args.write:
        write()
        return 0
    failures = check()
    if failures:
        for failure in failures:
            print(f"m5_census: FAIL {failure}")
        return 1
    state = build_m5_state()
    print(
        "m5_census: PASS "
        f"({len(state.locations):,} populated, "
        f"{len(state.route_edges):,} authored route edges / 0 runtime, "
        f"{len(markets())} markets)"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
