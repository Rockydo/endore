def _installed_cultures() -> tuple[str, ...]:
    # This private helper is the binding installed-registry parser already used
    # by the proven M4 runtime generator.
    from m2_runtime import _installed_definitions

    return tuple(_installed_definitions("cultures", exclude_inactive=True))


def _resolve_location(ref: str) -> str:
    state = build_state()
    key = state.ref_to_location.get(ref, ref)
    if key not in state.model.by_key:
        raise ValueError(f"unresolved M5 location reference {ref}")
    return key


def _nonruin_land() -> list[str]:
    state = build_state()
    return [
        location.key
        for location in state.model.locations
        if location.kind == "land" and state.rank[location.key] != "ruin"
    ]


def _abi_assignments(
    keys: list[str],
    custom_units: dict[str, int],
) -> dict[str, tuple[str, ...]]:
    cultures = _installed_cultures()
    ranked = sorted(
        keys,
        key=lambda key: (custom_units[key], key),
        reverse=True,
    )
    if len(ranked) < len(cultures):
        raise ValueError("not enough custom-dominant locations for installed culture ABI")
    hosts = ranked[: len(cultures)]
    if custom_units[hosts[-1]] < MIN_ABI_HOST_UNITS:
        raise ValueError(
            "installed culture ABI host population falls below "
            f"{MIN_ABI_HOST_UNITS / 1000:.1f}k"
        )
    result: dict[str, list[str]] = defaultdict(list)
    for culture, key in zip(cultures, hosts, strict=True):
        result[key].append(culture)
    return {key: tuple(values) for key, values in result.items()}


def _location_weight(model: WorldModel, key: str, rank: str) -> float:
    location = model.by_key[key]
    rank_weight = {
        "capital": 14.0,
        "city": 10.0,
        "town": 6.0,
        "port": 6.0,
        "fortress": 5.0,
        "hold": 5.0,
        "refuge": 4.0,
        "village": 3.0,
        "camp": 1.5,
        "landmark": 1.0,
        "place": 1.0,
        "wilderness": 0.18,
    }.get(rank, 1.0)
    density = float(model.density[location.y, location.x]) / 255.0
    biome_factor = {
        1: 1.20,
        2: 0.85,
        3: 0.65,
        4: 0.45,
        5: 0.25,
        6: 0.35,
        8: 0.20,
        9: 0.90,
        10: 0.35,
    }.get(location.biome_id, 0.75)
    area_factor = max(
        0.65,
        min(1.50, math.sqrt(float(model.areas[location.index]) / 70.0)),
    )
    return rank_weight * (0.35 + 1.65 * density) * biome_factor * area_factor


def _allocate_units(
    total_units: int,
    keys: list[str],
    weights: dict[str, float],
    minima: dict[str, int],
    preferred: str,
) -> dict[str, int]:
    minimum_total = sum(minima[key] for key in keys)
    if minimum_total > total_units:
        raise ValueError(
            f"minimum census {minimum_total / 1000:.3f} exceeds "
            f"target {total_units / 1000:.3f}"
        )
    residual = total_units - minimum_total
    weight_total = sum(weights[key] for key in keys)
    raw = {
        key: (residual * weights[key] / weight_total if weight_total else 0.0)
        for key in keys
    }
    additions = {key: int(math.floor(value)) for key, value in raw.items()}
    remainder = residual - sum(additions.values())
    order = sorted(
        keys,
        key=lambda key: (raw[key] - additions[key], key == preferred, key),
        reverse=True,
    )
    for key in order[:remainder]:
        additions[key] += 1
    return {key: minima[key] + additions[key] for key in keys}


def _split_types(units: int, profile: PopulationProfile) -> list[tuple[str, int]]:
    if units < 50:
        index = max(range(len(POP_TYPES)), key=lambda value: profile.shares[value])
        return [(POP_TYPES[index], units)]
    raw = [units * share for share in profile.shares]
    values = [int(math.floor(value)) for value in raw]
    remainder = units - sum(values)
    order = sorted(
        range(len(values)),
        key=lambda index: (raw[index] - values[index], -index),
        reverse=True,
    )
    for index in order[:remainder]:
        values[index] += 1
    return [
        (pop_type, value)
        for pop_type, value in zip(POP_TYPES, values, strict=True)
        if value
    ]


def _cap_type_split(
    values: list[tuple[str, int]],
    maximum: int,
) -> list[tuple[str, int]]:
    """Merge the smallest strata until all reserved setup slots remain available."""
    result = list(values)
    while len(result) > maximum:
        smallest = min(range(len(result)), key=lambda index: result[index][1])
        _, units = result.pop(smallest)
        largest = max(range(len(result)), key=lambda index: result[index][1])
        pop_type, current = result[largest]
        result[largest] = (pop_type, current + units)
    return result


def _base_raw_materials(model: WorldModel) -> dict[str, str]:
    coast = set(coastal_edges(model))
    dominant_biomes = effective_template_biomes(model)
    result: dict[str, str] = {}
    for location in model.locations:
        if location.kind != "land":
            continue
        token = int.from_bytes(
            hashlib.sha256(location.key.encode("utf-8")).digest()[:4],
            "little",
        )
        biome_id = int(dominant_biomes[location.index])
        biome_choices = {
            1: ("wheat", "livestock", "clay", "wool"),
            # Forests are continuous material/object fields rather than
            # location-template terrain.  The playable templates deliberately
            # remain grasslands so their borders cannot appear as Voronoi
            # patches in the close renderer; lumber's installed
            # location_potential therefore rejects these otherwise wooded
            # cells.  Keep only goods whose potential accepts the neutral
            # template until a seamless forest terrain contract is proven.
            2: ("wild_game", "wool", "medicaments"),
            3: ("wild_game", "medicaments", "wool"),
            4: ("stone", "iron", "copper", "gems"),
            5: ("fur", "wild_game", "fish"),
            6: ("medicaments", "fish", "clay"),
            8: ("iron", "stone", "salt"),
            9: ("horses", "livestock", "wool", "wheat"),
            10: ("livestock", "salt", "wool", "copper"),
        }.get(biome_id, ("wheat", "livestock", "clay"))
        good = biome_choices[token % len(biome_choices)]
        if location.index in coast and token % 4 == 0:
            good = "fish"
        if location.region == "me_rohan_region" and token % 3 == 0:
            good = "horses"
        elif location.region == "me_shire_breeland_region":
            good = ("wheat", "wool", "fiber_crops")[token % 3]
        elif location.region == "me_mordor_region":
            good = ("iron", "stone", "wheat", "livestock")[token % 4]
        elif location.region == "me_forochel_region":
            good = ("fur", "fish", "wild_game")[token % 3]
        result[location.key] = good

    state = build_state()
    special = {
        "hobbiton": "fiber_crops",
        "michel_delving": "wheat",
        "bucklebury": "wheat",
        "edoras": "horses",
        "helms_deep": "gems",
        "pelargir": "fish",
        "dol_amroth": "fish",
        "umbar": "fish",
        "erebor": "goods_gold",
        "iron_hills": "iron",
        "moria": "gems",
        "dorwinion": "wine",
        "me_land_5092": "wheat",
        state.ref_to_location["forochel_camp"]: "fur",
    }
    for ref, good in special.items():
        key = _resolve_location(ref)
        if key in result:
            result[key] = good
    return result


def _base_settlements() -> dict[str, tuple[str, str, int]]:
    people = assignments()
    political = build_state()
    result: dict[str, tuple[str, str, int]] = {}
    for key, person in people.items():
        rank = political.rank[key]
        value: tuple[str, str, int] | None = None
        if rank in {"capital", "city"}:
            value = ("city", "me_m5_city", 8)
        elif rank == "town":
            value = ("town", "me_m5_town", 4)
        elif rank == "port":
            value = ("town", "me_m5_town_port", 4)
        elif rank == "fortress":
            value = ("town", "me_m5_fortress", 4)
        elif rank == "refuge":
            value = ("town", "me_m5_refuge", 3)
        elif rank == "hold":
            setup = (
                "me_m5_dwarf_hold"
                if person.culture in {"me_longbeard", "me_firebeard_broadbeam"}
                else "me_m5_shadow_hold"
            )
            value = ("town", setup, 4)
        if value:
            result[key] = value

    for realm in political.realms:
        capital = political.ref_to_location[realm.capital_ref]
        if capital not in result:
            culture = people[capital].culture
            setup = (
                "me_m5_dwarf_hold"
                if culture in {"me_longbeard", "me_firebeard_broadbeam"}
                else "me_m5_town"
            )
            result[capital] = ("town", setup, 3)

    for market in markets():
        key = _resolve_location(market.location)
        result.setdefault(key, ("town", "me_m5_town", 3))
    for override in settlement_overrides().values():
        key = _resolve_location(override.location)
        result[key] = (
            override.engine_rank,
            override.town_setup,
            override.development_bonus,
        )
    return result


@lru_cache(maxsize=1)
def _land_graph() -> dict[int, tuple[int, ...]]:
    model = build_model()
    land = np.array(
        [location.kind == "land" for location in model.locations],
        dtype=bool,
    )
    graph: dict[int, set[int]] = defaultdict(set)
    for first, second in (
        (model.labels[:, :-1], model.labels[:, 1:]),
        (model.labels[:-1, :], model.labels[1:, :]),
    ):
        mask = first != second
        for a, b in zip(first[mask].tolist(), second[mask].tolist(), strict=True):
            a = int(a)
            b = int(b)
            if land[a] and land[b]:
                graph[a].add(b)
                graph[b].add(a)
    return {key: tuple(sorted(values)) for key, values in graph.items()}


def _shortest_land_path(start_key: str, end_key: str) -> tuple[int, ...]:
    model = build_model()
    start_key = _resolve_location(start_key)
    end_key = _resolve_location(end_key)
    start = model.by_key[start_key].index
    end = model.by_key[end_key].index
    graph = _land_graph()
    end_location = model.locations[end]

    def heuristic(index: int) -> float:
        location = model.locations[index]
        return math.hypot(
            location.x - end_location.x,
            location.y - end_location.y,
        ) / 32.0

    queue: list[tuple[float, float, int]] = [(heuristic(start), 0.0, start)]
    previous: dict[int, int] = {}
    best = {start: 0.0}
    while queue:
        _, cost, current = heapq.heappop(queue)
        if current == end:
            break
        if cost != best.get(current):
            continue
        for neighbor in graph.get(current, ()):
            biome = model.locations[neighbor].biome_id
            step = 1.0 + (0.35 if biome in {3, 5, 6, 8, 10} else 0.0)
            new_cost = cost + step
            if new_cost < best.get(neighbor, float("inf")):
                best[neighbor] = new_cost
                previous[neighbor] = current
                heapq.heappush(
                    queue,
                    (new_cost + heuristic(neighbor), new_cost, neighbor),
                )
    if end not in best:
        raise ValueError(f"no passable road path from {start_key} to {end_key}")
    path = [end]
    while path[-1] != start:
        path.append(previous[path[-1]])
    return tuple(reversed(path))


def _roads() -> tuple[tuple[tuple[str, str], ...], dict[str, int]]:
    model = build_model()
    all_edges: set[tuple[int, int]] = set()
    counts: dict[str, int] = {}
    for route in routes():
        route_edges: set[tuple[int, int]] = set()
        for start, end in zip(route.waypoints, route.waypoints[1:]):
            path = _shortest_land_path(start, end)
            for a, b in zip(path, path[1:]):
                edge = (a, b) if a < b else (b, a)
                all_edges.add(edge)
                route_edges.add(edge)
        counts[route.key] = len(route_edges)
    rendered = tuple(
        (model.locations[a].key, model.locations[b].key)
        for a, b in sorted(all_edges)
    )
    return rendered, counts


@lru_cache(maxsize=1)
def build_m5_state() -> M5State:
    political = build_state()
    people = assignments()
    profiles = population_profiles()
    targets = realm_census()
    keys = _nonruin_land()
    by_realm: dict[str, list[str]] = defaultdict(list)
    for key in keys:
        by_realm[political.ownership[key]].append(key)

    majority_units: dict[str, int] = {}
    profile_by_location: dict[str, PopulationProfile] = {}
    minority_by_location: dict[str, PopEntry] = {}
    for tag, target in targets.items():
        realm_keys = by_realm[tag]
        weights = {
            key: _location_weight(political.model, key, political.rank[key])
            for key in realm_keys
        }
        realm_majority_units = target.total_units - target.minority_units
        # A fixed five-unit floor can exceed a small realm's canonical target
        # even on the reduced 12,104-location world. Keep every non-ruin
        # location inhabited, scale the floor to local cell density, and
        # reserve at least half the census for geographic/rank weighting.
        minimum_per_location = min(
            5,
            max(
                1,
                realm_majority_units // max(1, len(realm_keys) * 2),
            ),
        )
        minima = {
            key: minimum_per_location
            for key in realm_keys
        }
        if tag == WILD:
            preferred = max(realm_keys, key=lambda key: weights[key])
        else:
            realm = political.by_tag[tag]
            preferred = political.ref_to_location[realm.capital_ref]
        allocation = _allocate_units(
            realm_majority_units,
            realm_keys,
            weights,
            minima,
            preferred,
        )
        profile = profiles[target.profile]
        for key in realm_keys:
            majority_units[key] = allocation[key]
            profile_by_location[key] = profile
        if target.minority_units:
            key = _resolve_location(target.minority_location)
            minority_by_location[key] = PopEntry(
                target.minority_type,
                target.minority_units,
                target.minority_culture,
                target.minority_faith,
            )

    custom_units = dict(majority_units)
    for key, minority in minority_by_location.items():
        custom_units[key] += minority.units
    abi = _abi_assignments(keys, custom_units)

    locations: dict[str, CensusLocation] = {}
    for key in keys:
        person = people[key]
        split = _split_types(
            majority_units[key],
            profile_by_location[key],
        )
        reserved_slots = (1 if key in abi else 0) + (
            1 if key in minority_by_location else 0
        )
        split = _cap_type_split(
            split,
            MAX_SETUP_POP_ENTRIES - reserved_slots,
        )
        entries = [
            PopEntry(pop_type, units, person.culture, person.faith)
            for pop_type, units in split
        ]
        locations[key] = CensusLocation(
            location=key,
            realm=political.ownership[key],
            custom_units=custom_units[key],
            entries=tuple(entries),
        )
        if key in minority_by_location:
            current = locations[key]
            minority = minority_by_location[key]
            locations[key] = CensusLocation(
                location=key,
                realm=current.realm,
                custom_units=current.custom_units,
                entries=current.entries + (minority,),
            )

    for key, culture_keys in abi.items():
        current = locations[key]
        technical = tuple(
            PopEntry(
                "peasants",
                10,
                culture,
                "me_valar_worship",
                technical_abi=True,
            )
            for culture in culture_keys
        )
        locations[key] = CensusLocation(
            location=key,
            realm=current.realm,
            custom_units=current.custom_units,
            entries=current.entries + technical,
        )

    route_edges, route_counts = _roads()
    return M5State(
        locations=locations,
        abi_cultures=abi,
        raw_materials=_base_raw_materials(political.model),
        settlements=_base_settlements(),
        route_edges=route_edges,
        route_edge_counts=route_counts,
    )


def raw_materials() -> dict[str, str]:
    return build_m5_state().raw_materials


def _format_units(units: int) -> str:
    return f"{units / 1000:.3f}".rstrip("0").rstrip(".")


def _pops_payload(state: M5State) -> str:
    lines = [M5_MARKER, "locations = {"]
    for key in _nonruin_land():
        location = state.locations[key]
        lines.append(f"\t{key} = {{")
        for pop in location.entries:
            suffix = " # installed culture ABI" if pop.technical_abi else ""
            lines.append(
                "\t\tdefine_pop = { "
                f"type = {pop.pop_type} size = {_format_units(pop.units)} "
                f"culture = {pop.culture} religion = {pop.faith} "
                f"}}{suffix}"
            )
        lines.append("\t}")
    lines.append("}")
    return "\n".join(lines) + "\n"


def _markets_payload() -> str:
    lines = [M5_MARKER, "market_manager = {"]
    lines.extend(
        f"\tadd_market = {_resolve_location(market.location)}"
        for market in markets()
    )
    lines.append("}")
    return "\n".join(lines) + "\n"


def _settlements_payload(state: M5State) -> str:
    lines = [M5_MARKER, "locations = {"]
    for key, (rank, setup, _) in sorted(state.settlements.items()):
        lines.append(
            f"\t{key} = {{ rank = {rank} town_setup = {setup} }}"
        )
    lines.extend(("}", "building_manager = {", "}"))
    return "\n".join(lines) + "\n"


def _roads_payload() -> str:
    # The 302 authored edges are retained and validated in the route ledger, but
    # EU5 renders a starting road only when the edge also has an Arda-native
    # strip in spline_network.splnet.  Shipping the gameplay graph without that
    # binary produces one runtime diagnostic per edge; retaining the installed
    # Earth binary would violate the custom-map contract.  Keep runtime empty
    # until a materially different spline-serialization route succeeds.
    return (
        f"{M5_MARKER}\n"
        "# Deferred: authored routes lack an Arda-native spline network.\n"
        "road_network = {\n}\n"
    )


def _development_payload(state: M5State) -> str:
    model = build_model()
    by_region: dict[str, list[float]] = defaultdict(list)
    for location in model.locations:
        if location.kind == "land":
            by_region[location.region].append(
                float(model.density[location.y, location.x])
            )
    lines = [
        M5_MARKER,
        "development = {",
        "\tbase = 0",
        "\troad = 1",
        "\tcity = 5",
        "\ttown = 2",
    ]
    for region, values in sorted(by_region.items()):
        bonus = round(float(np.mean(values)) / 255.0 * 10.0)
        lines.append(f"\t{region} = {bonus}")
    for key, (_, _, bonus) in sorted(state.settlements.items()):
        if bonus:
            lines.append(f"\t{key} = {bonus}")
    lines.append("}")
    return "\n".join(lines) + "\n"


def _armies_payload() -> str:
    political = build_state()
    targets = realm_census()
    lines = [M5_MARKER, "unit_manager = {"]
    for realm in political.realms:
        target = targets[realm.tag].total_units
        count = (
            7
            if target >= 1_000_000
            else 5
            if target >= 500_000
            else 4
            if target >= 200_000
            else 3
            if target >= 50_000
            else 2
            if target >= 10_000
            else 1
        )
        capital = political.ref_to_location[realm.capital_ref]
        lines.extend(
            (
                "\tarmy = {",
                f"\t\tcountry = {realm.tag}",
                f"\t\tlocation = {capital}",
                "\t\tsub_units = {",
            )
        )
        lines.extend(
            "\t\t\ta_footmen = { strength = 1 }"
            for _ in range(count)
        )
        lines.extend(("\t\t}", "\t\tmorale = 1", "\t}", ""))
    lines.append("}")
    return "\n".join(lines) + "\n"


