def load_realms() -> tuple[Realm, ...]:
    with REALMS_CSV.open("r", encoding="utf-8-sig", newline="") as handle:
        rows = list(csv.DictReader(handle))
    return tuple(
        Realm(
            tag=row["tag"],
            name=row["name"],
            adjective=row["adjective"],
            capital_ref=row["capital_ref"],
            x=float(row["x"]),
            y=float(row["y"]),
            regions=frozenset(row["regions"].split("|")),
            style=row["style"],
            color=tuple(int(value) for value in row["color"].split()),
            emblem=row["emblem"],
            max_locations=int(row["max_locations"]),
            source=row["source"],
        )
        for row in rows
    )


