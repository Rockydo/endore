def normalized_distance(location: Location, x: float, y: float) -> float:
    lx, ly = location.normalized
    # The 2:1 canvas makes horizontal and vertical strategic distances
    # comparable only after compressing the x term.
    return ((lx - x) * 0.72) ** 2 + (ly - y) ** 2


def resolve_landmarks(
    model: WorldModel,
) -> tuple[dict[str, str], dict[str, Landmark]]:
    anchors = load_anchors()
    land = [location for location in model.locations if location.kind == "land"]
    anchor_locations = [location for location in land if location.anchor]
    ref_to_location: dict[str, str] = {}
    reserved: set[str] = set()
    for anchor in anchors:
        location = min(
            anchor_locations,
            key=lambda item: normalized_distance(item, anchor.x, anchor.y),
        )
        ref_to_location[anchor.key] = location.key
        reserved.add(location.key)

    landmark_by_location: dict[str, Landmark] = {}
    for landmark in load_landmarks():
        if landmark.ref in ref_to_location:
            continue
        candidates = [location for location in land if location.key not in reserved]
        location = min(
            candidates,
            key=lambda item: normalized_distance(item, landmark.x, landmark.y),
        )
        ref_to_location[landmark.ref] = location.key
        landmark_by_location[location.key] = landmark
        reserved.add(location.key)
    return ref_to_location, landmark_by_location


def wilderness_reason(location: Location, protected: set[str]) -> str | None:
    if location.key in protected:
        return None
    x, y = location.normalized
    if location.region == "me_northern_wastes_region" and y < 0.155:
        return "wild_forodwaith"
    if (
        location.region == "me_enedwaith_region"
        and x < 0.39
        and 0.50 < y < 0.65
    ):
        return "wild_enedwaith"
    if (
        location.region == "me_brown_lands_region"
        and location.biome_id in {6, 8}
        and x < 0.70
    ):
        return "wild_brown_lands"
    if (
        location.region == "me_ithilien_region"
        and 0.645 < x < 0.690
        and 0.650 < y < 0.790
    ):
        return "wild_ithilien"
    return None


def assign_ownership(
    model: WorldModel,
    realms: tuple[Realm, ...],
    ref_to_location: dict[str, str],
) -> tuple[dict[str, str], dict[str, str]]:
    ownership: dict[str, str] = {}
    wild_reason: dict[str, str] = {}
    counts: Counter[str] = Counter()
    by_tag = {realm.tag: realm for realm in realms}
    forced_owner = {
        ref_to_location[realm.capital_ref]: realm.tag
        for realm in realms
    }
    if len(forced_owner) != len(realms):
        raise ValueError("two M3 realms resolve to the same capital location")
    hint_owner = {
        "Lindon": "LIN",
        "Angmar": "ANG",
        "Shire": "SHI",
        "Bree-land": "BRE",
        "Imladris": "RIV",
        "Misty Mountains": "GOB",
        "Gundabad": "GUN",
        "Moria": "MOA",
        "Beornings": "BEO",
        "Lothlórien": "LOR",
        "Dol Guldur": "DOL",
        "Woodland Realm": "WOO",
        "Lake-town": "ESG",
        "Dale": "DAL",
        "Erebor": "ERE",
        "Dorwinion": "DOR",
        "Isengard": "ISE",
        "Rohan": "ROH",
        "Gondor": "GON",
        "Mordor": "MOR",
        "Umbar": "UMB",
    }
    anchor_rank = {anchor.key: anchor.rank for anchor in load_anchors()}
    anchor_hint = {anchor.key: anchor.realm_hint for anchor in load_anchors()}
    for ref, location_key in ref_to_location.items():
        if ref not in anchor_hint or anchor_rank[ref] == "ruin":
            continue
        tag = hint_owner.get(anchor_hint[ref])
        if ref == "dol_amroth":
            tag = "DAM"
        if tag:
            forced_owner[location_key] = tag
    for key, tag in forced_owner.items():
        ownership[key] = tag
        counts[tag] += 1

    candidates_by_region: dict[str, list[Realm]] = defaultdict(list)
    for realm in realms:
        for region in realm.regions:
            candidates_by_region[region].append(realm)

    unassigned = [
        location
        for location in model.locations
        if location.kind == "land" and location.key not in ownership
    ]
    # Allocate the strongest Voronoi claims first so deliberately tiny realms
    # retain the compact heartland nearest their seat.
    scored: list[tuple[float, str, Location, list[tuple[float, Realm]]]] = []
    protected = set(forced_owner)
    for location in unassigned:
        reason = wilderness_reason(location, protected)
        if reason:
            ownership[location.key] = WILD
            wild_reason[location.key] = reason
            continue
        choices = sorted(
            (
                normalized_distance(location, realm.x, realm.y),
                realm,
            )
            for realm in candidates_by_region.get(location.region, ())
        )
        if not choices:
            ownership[location.key] = WILD
            wild_reason[location.key] = "wild_unclaimed"
            continue
        scored.append((choices[0][0], location.key, location, choices))
    for _, _, location, choices in sorted(scored):
        chosen: Realm | None = None
        for _, realm in choices:
            if realm.max_locations == 0 or counts[realm.tag] < realm.max_locations:
                chosen = realm
                break
        if chosen is None:
            ownership[location.key] = WILD
            wild_reason[location.key] = "wild_buffer"
        else:
            ownership[location.key] = chosen.tag
            counts[chosen.tag] += 1

    for location in model.locations:
        if location.kind != "land":
            ownership[location.key] = WILD
            wild_reason[location.key] = f"wild_{location.kind}"
    for tag in by_tag:
        if counts[tag] < 1:
            raise ValueError(f"{tag} owns no location")
    return ownership, wild_reason


def generated_compound(style: str, serial: int) -> str:
    first, second, third = STYLE_PARTS[style]
    base_count = len(first) * len(second) * len(third)
    base_serial = serial % base_count
    cycle = serial // base_count
    a = first[base_serial % len(first)]
    b = second[(base_serial // len(first)) % len(second)]
    c = third[(base_serial // (len(first) * len(second))) % len(third)]
    if style in {"sindarin"}:
        result = f"{a} {b}{c}"
    else:
        result = f"{a}{b}{c}"
    if cycle:
        # Productive "of X" compounds keep the generated lexicon finite-state
        # and deterministic without ever exposing engineering ordinals.
        qualifier_serial = cycle - 1
        qa = first[qualifier_serial % len(first)]
        qb = second[(qualifier_serial // len(first)) % len(second)]
        qualifier = f"{qa} {qb}" if style == "sindarin" else f"{qa}{qb}"
        result = f"{result} of {qualifier}"
    return result


def all_location_names(
    model: WorldModel,
    ownership: dict[str, str],
    by_tag: dict[str, Realm],
    landmark_by_location: dict[str, Landmark],
) -> tuple[dict[str, str], dict[str, str], dict[str, str]]:
    anchor_by_name = {anchor.name: anchor for anchor in load_anchors()}
    names: dict[str, str] = {}
    ranks: dict[str, str] = {}
    sources: dict[str, str] = {}
    used: set[str] = set()
    counters: Counter[tuple[str, str]] = Counter()
    for location in model.locations:
        if location.anchor:
            anchor = anchor_by_name[location.display_name]
            name = anchor.name
            rank = anchor.rank
            source = anchor.source
        elif location.key in landmark_by_location:
            landmark = landmark_by_location[location.key]
            name = landmark.name
            rank = landmark.rank
            source = landmark.source
        else:
            owner = ownership[location.key]
            style = (
                by_tag[owner].style
                if owner != WILD
                else REGION_STYLE[location.region]
            )
            counter_key = (style, location.kind)
            serial = counters[counter_key]
            while True:
                compound = generated_compound(style, serial)
                if location.kind == "mountain":
                    name = (
                        f"Ered {compound}"
                        if style == "sindarin"
                        else f"{compound} Heights"
                    )
                elif location.kind == "lake":
                    name = (
                        f"Nen {compound}"
                        if style == "sindarin"
                        else f"Lake {compound}"
                    )
                elif location.kind == "sea":
                    name = (
                        f"Bay of {compound}"
                        if serial % 3 == 0
                        else f"{compound} Reach"
                    )
                else:
                    name = compound
                serial += 1
                if name not in used:
                    break
            counters[counter_key] = serial
            rank = "wilderness" if owner == WILD else "place"
            source = "† M3 regional lexicon"
        if name in used:
            raise ValueError(f"duplicate M3 display name: {name}")
        used.add(name)
        names[location.key] = name
        ranks[location.key] = rank
        sources[location.key] = source
    return names, ranks, sources


@lru_cache(maxsize=1)
def build_state() -> RealmState:
    model = build_model()
    realms = load_realms()
    by_tag = {realm.tag: realm for realm in realms}
    ref_to_location, landmark_by_location = resolve_landmarks(model)
    ownership, wild_reason = assign_ownership(model, realms, ref_to_location)
    names, rank, source = all_location_names(
        model,
        ownership,
        by_tag,
        landmark_by_location,
    )
    return RealmState(
        model=model,
        realms=realms,
        by_tag=by_tag,
        ref_to_location=ref_to_location,
        landmark_by_location=landmark_by_location,
        ownership=ownership,
        wild_reason=wild_reason,
        names=names,
        rank=rank,
        source=source,
    )


def location_names(model: WorldModel | None = None) -> dict[str, str]:
    state = build_state()
    if model is not None and len(model.locations) != len(state.model.locations):
        raise ValueError("M3 naming model differs from M2 world model")
    return dict(state.names)


def physical_alignment(state: RealmState) -> dict[str, object]:
    """Prove political ownership and capitals sit on authored dry land."""
    with Image.open(CONTROL / "elevation.png") as image:
        elevation = np.asarray(image, dtype=np.uint16)
    if elevation.shape != state.model.labels.shape:
        raise ValueError(
            f"elevation shape {elevation.shape} differs from political labels "
            f"{state.model.labels.shape}"
        )
    owned_index = np.array(
        [
            state.ownership[location.key] != WILD
            for location in state.model.locations
        ],
        dtype=bool,
    )
    owned_pixels = owned_index[state.model.labels]
    wet_owned_pixels = int(
        np.count_nonzero(
            owned_pixels & (elevation <= ENGINE_WATER_LEVEL_SAMPLE)
        )
    )
    capitals: dict[str, dict[str, object]] = {}
    maximum_snap_distance = 0.0
    for realm in state.realms:
        key = state.ref_to_location[realm.capital_ref]
        location = state.model.by_key[key]
        distance = normalized_distance(location, realm.x, realm.y) ** 0.5
        maximum_snap_distance = max(maximum_snap_distance, distance)
        capitals[realm.tag] = {
            "location": key,
            "kind": location.kind,
            "normalized": [
                round(location.normalized[0], 6),
                round(location.normalized[1], 6),
            ],
            "authored": [realm.x, realm.y],
            "snap_distance": round(distance, 6),
            "raw_height": int(elevation[location.y, location.x]),
        }
    return {
        "engine_water_level_sample": ENGINE_WATER_LEVEL_SAMPLE,
        "owned_control_pixels": int(np.count_nonzero(owned_pixels)),
        "wet_owned_control_pixels": wet_owned_pixels,
        "maximum_capital_snap_distance": round(maximum_snap_distance, 6),
        "capitals": capitals,
    }


def political_qa_png(state: RealmState) -> bytes:
    """Render the exact ownership lookup over the physical control raster."""
    palette = np.zeros((len(state.model.locations), 3), dtype=np.uint8)
    for location in state.model.locations:
        owner = state.ownership[location.key]
        if owner != WILD:
            palette[location.index] = state.by_tag[owner].color
        elif location.kind == "sea":
            palette[location.index] = (20, 48, 72)
        elif location.kind == "lake":
            palette[location.index] = (30, 72, 88)
        elif location.kind == "mountain":
            palette[location.index] = (58, 56, 52)
        else:
            palette[location.index] = (118, 112, 96)
    image = Image.fromarray(palette[state.model.labels], mode="RGB")
    draw = ImageDraw.Draw(image)
    for realm in state.realms:
        location = state.model.by_key[
            state.ref_to_location[realm.capital_ref]
        ]
        x, y = location.x, location.y
        draw.rectangle((x - 2, y - 2, x + 2, y + 2), fill=(8, 8, 8))
        draw.point((x, y), fill=(255, 255, 255))
    output = io.BytesIO()
    image.save(output, format="PNG", compress_level=9)
    return output.getvalue()


