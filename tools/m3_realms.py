def normalized_distance(location: Location, x: float, y: float) -> float:
    lx, ly = location.normalized
    # Normalized x spans a canvas twice as wide as normalized y. The source
    # projection preserves equal physical scale, so x must be expanded by two
    # when comparing strategic distances.
    return ((lx - x) * 2.0) ** 2 + (ly - y) ** 2


def point_in_polygon(
    x: float,
    y: float,
    polygon: tuple[tuple[float, float], ...],
) -> bool:
    """Return whether an equal-scale source point lies inside a simple polygon."""

    inside = False
    previous_x, previous_y = polygon[-1]
    for current_x, current_y in polygon:
        if (current_y > y) != (previous_y > y):
            crossing_x = (
                (previous_x - current_x)
                * (y - current_y)
                / (previous_y - current_y)
                + current_x
            )
            if x < crossing_x:
                inside = not inside
        previous_x, previous_y = current_x, current_y
    return inside


def source_zone_location_claims(model: WorldModel) -> dict[str, frozenset[str]]:
    """Map source woodland polygons to every substantially overlapping location."""

    # Local import avoids coupling the political module's basic data types to the
    # renderer generator while sharing its exact hash-pinned/naturalized mask routine.
    from gen_map_objects import named_forest_mask

    result: dict[str, frozenset[str]] = {}
    for tag, (zone, dilation, _) in SOURCE_ZONE_CLAIMS.items():
        mask = named_forest_mask(zone)
        if dilation:
            mask = np.asarray(
                Image.fromarray(mask.astype(np.uint8) * 255, "L").filter(
                    ImageFilter.MaxFilter(dilation * 2 + 1)
                ),
                dtype=np.uint8,
            ) > 0
        overlap = np.bincount(
            model.labels[mask].astype(np.int64),
            minlength=len(model.locations),
        )
        # Sixteen source pixels is well below a typical location's area but rejects a
        # one-pixel tangency. Full location assignment then stays jagged and contiguous
        # without turning the source polygon into a cadastral rectangle.
        result[tag] = frozenset(
            location.key
            for location in model.locations
            if location.kind == "land" and overlap[location.index] >= 16
        )
    return result


def claim_contract(
    location: Location,
    realm: Realm,
    source_zone_claims: dict[str, frozenset[str]],
) -> tuple[bool, str]:
    """Apply reviewed physical-frontier contracts before political allocation."""
    source_contract = SOURCE_ZONE_CLAIMS.get(realm.tag)
    if source_contract is not None:
        allowed = location.key in source_zone_claims[realm.tag]
        rationales = [source_contract[2]]
        bounds = CLAIM_BOUNDS.get(realm.tag)
        if bounds is not None:
            x0, x1, y0, y1, _ = bounds
            x, y = location.normalized
            allowed = allowed and x0 <= x <= x1 and y0 <= y <= y1
            rationales.append(bounds[4])
        polygon_contract = CLAIM_POLYGONS.get(realm.tag)
        if polygon_contract is not None:
            polygon, rationale = polygon_contract
            allowed = allowed and point_in_polygon(
                *location.normalized,
                polygon,
            )
            rationales.append(rationale)
        return allowed, "; ".join(rationales)
    polygon_contract = CLAIM_POLYGONS.get(realm.tag)
    if polygon_contract is not None:
        polygon, rationale = polygon_contract
        return point_in_polygon(*location.normalized, polygon), rationale
    contract = CLAIM_BOUNDS.get(realm.tag)
    if contract is None:
        return True, "reviewed_region_claim"
    x0, x1, y0, y1, rationale = contract
    x, y = location.normalized
    if x0 <= x <= x1 and y0 <= y <= y1:
        return True, rationale
    return False, rationale


def resolve_landmarks(
    model: WorldModel,
) -> tuple[dict[str, str], dict[str, Landmark]]:
    anchors = load_anchors()
    land = [location for location in model.locations if location.kind == "land"]
    anchor_locations = [location for location in land if location.anchor]
    ref_to_location: dict[str, str] = {}
    reserved: set[str] = set()
    for anchor in anchors:
        location = min(
            anchor_locations,
            key=lambda item: normalized_distance(item, anchor.x, anchor.y),
        )
        ref_to_location[anchor.key] = location.key
        reserved.add(location.key)

    landmark_by_location: dict[str, Landmark] = {}
    for landmark in load_landmarks():
        if landmark.ref in ref_to_location:
            continue
        candidates = [location for location in land if location.key not in reserved]
        location = min(
            candidates,
            key=lambda item: normalized_distance(item, landmark.x, landmark.y),
        )
        ref_to_location[landmark.ref] = location.key
        landmark_by_location[location.key] = landmark
        reserved.add(location.key)
    return ref_to_location, landmark_by_location


def wilderness_reason(location: Location, protected: set[str]) -> str | None:
    if location.key in protected:
        return None
    x, y = location.normalized
    if location.region == "me_northern_wastes_region" and y < 0.155:
        return "wild_forodwaith"
    if (
        location.region == "me_enedwaith_region"
        and x < 0.42
        and 0.36 < y < 0.53
    ):
        return "wild_enedwaith"
    if (
        location.region == "me_brown_lands_region"
        and location.biome_id in {6, 8}
        and x < 0.62
    ):
        return "wild_brown_lands"
    if location.region == "me_ithilien_region":
        return "wild_ithilien"
    return None


