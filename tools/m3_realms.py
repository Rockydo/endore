def check() -> list[str]:
    failures: list[str] = []
    state = build_state()
    realms = state.realms
    if len(realms) != EXPECTED_REALM_COUNT:
        failures.append(
            f"realm roster has {len(realms)} rows, expected {EXPECTED_REALM_COUNT}"
        )
    tags = [realm.tag for realm in realms]
    if len(tags) != len(set(tags)):
        failures.append("realm roster repeats a tag")
    if any(not re.fullmatch(r"[A-Z0-9]{3}", tag) for tag in tags):
        failures.append("every realm tag must be exactly three uppercase alphanumerics")
    colors = [realm.color for realm in realms]
    if len(colors) != len(set(colors)):
        failures.append("realm map colors are not unique")
    if any(realm.style not in STYLE_PARTS for realm in realms):
        failures.append("realm roster uses an undefined naming style")
    alignment = physical_alignment(state)
    if alignment["wet_owned_control_pixels"]:
        failures.append(
            "political ownership paints "
            f"{alignment['wet_owned_control_pixels']} below-water control pixels"
        )
    if alignment["maximum_capital_snap_distance"] > 0.025:
        failures.append(
            "a realm capital snaps too far from its authored position: "
            f"{alignment['maximum_capital_snap_distance']:.6f}"
        )
    audit_rows = ownership_audit_rows(state)
    contract_violations = [
        row for row in audit_rows if row["verdict"] == "violation"
    ]
    if contract_violations:
        failures.append(
            "political claim contracts reject final locations: "
            f"{contract_violations[:5]}"
        )
    excessive_distance = [
        row
        for row in audit_rows
        if row["realm"] != WILD
        and row["realm"] not in CONTRACTED_TAGS
        and row["forced"] == "no"
        and row["distance_to_capital"]
        and float(row["distance_to_capital"]) > MAX_UNCONTRACTED_CAPITAL_DISTANCE
    ]
    if excessive_distance:
        failures.append(
            "uncontracted political claims exceed the anti-sprawl distance: "
            f"{excessive_distance[:5]}"
        )
    connectivity = realm_connectivity(state)
    fragmented_compact_realms = {
        tag: connectivity[tag]["component_detail"]
        for tag in CONTIGUOUS_CLAIM_REALMS
        if connectivity[tag]["components"] != 1
    }
    if fragmented_compact_realms:
        failures.append(
            "compact source-side realms contain detached political components: "
            f"{fragmented_compact_realms}"
        )
    for tag, (
        minimum,
        maximum,
        bbox,
        rationale,
    ) in POLITICAL_SILHOUETTE_CONTRACTS.items():
        owned = [
            location
            for location in state.model.locations
            if location.kind == "land" and state.ownership[location.key] == tag
        ]
        if not minimum <= len(owned) <= maximum:
            failures.append(
                f"{tag} silhouette owns {len(owned)} locations outside "
                f"reviewed range {minimum}..{maximum}: {rationale}"
            )
        x0, x1, y0, y1 = bbox
        outside = [
            location.key
            for location in owned
            if not (
                x0 <= location.normalized[0] <= x1
                and y0 <= location.normalized[1] <= y1
            )
        ]
        if outside:
            failures.append(
                f"{tag} silhouette escapes reviewed physical bbox {bbox}: "
                f"{outside[:5]} ({rationale})"
            )
    for ref, excluded_owners in FRONTIER_LANDMARK_EXCLUSIONS.items():
        location_key = state.ref_to_location.get(ref)
        if location_key is None:
            failures.append(f"political frontier landmark {ref} is unresolved")
            continue
        actual_owner = state.ownership[location_key]
        if actual_owner in excluded_owners:
            failures.append(
                f"political frontier landmark {ref} is incorrectly owned by "
                f"{actual_owner}; excluded owners are {sorted(excluded_owners)}"
            )
    unreviewed_components = {
        tag: [
            row
            for row in summary["component_detail"][1:]
            if row["disposition"] == "unreviewed"
        ]
        for tag, summary in connectivity.items()
        if any(
            row["disposition"] == "unreviewed"
            for row in summary["component_detail"][1:]
        )
    }
    if unreviewed_components:
        failures.append(
            "political components lack a physical disposition: "
            f"{unreviewed_components}"
        )
    regions = {location.region for location in state.model.locations}
    for realm in realms:
        unknown = realm.regions - regions
        if unknown:
            failures.append(f"{realm.tag} uses unknown regions: {sorted(unknown)}")
        capital = state.ref_to_location.get(realm.capital_ref)
        if capital is None:
            failures.append(f"{realm.tag} has unresolved capital {realm.capital_ref}")
        elif state.ownership.get(capital) != realm.tag:
            failures.append(f"{realm.tag} does not own its capital {capital}")
        elif state.model.by_key[capital].kind != "land":
            failures.append(f"{realm.tag} capital {capital} is not passable land")
        count = sum(value == realm.tag for value in state.ownership.values())
        if count < 1:
            failures.append(f"{realm.tag} owns no locations")
        reviewed_allowance = sum(
            target == realm.tag
            for target, _, _, _ in REVIEWED_COMPONENT_REPAIRS.values()
        )
        if (
            realm.max_locations
            and count > realm.max_locations + reviewed_allowance
        ):
            failures.append(
                f"{realm.tag} owns {count}, above allocator cap "
                f"{realm.max_locations} plus {reviewed_allowance} reviewed repairs"
            )
    if sum(value == "IRO" for value in state.ownership.values()) < 12:
        failures.append("Iron Hills lacks a viable source-side territorial cluster")
    parent = list(range(len(state.model.locations)))

    def find(value: int) -> int:
        while parent[value] != value:
            parent[value] = parent[parent[value]]
            value = parent[value]
        return value

    def union(left: int, right: int) -> None:
        left_root, right_root = find(left), find(right)
        if left_root != right_root:
            parent[right_root] = left_root

    labels = state.model.labels
    kind = [location.kind for location in state.model.locations]
    pairs = np.concatenate(
        (
            np.stack((labels[:, :-1].ravel(), labels[:, 1:].ravel()), axis=1),
            np.stack((labels[:-1, :].ravel(), labels[1:, :].ravel()), axis=1),
        )
    )
    for left, right in np.unique(pairs[pairs[:, 0] != pairs[:, 1]], axis=0):
        if kind[int(left)] == "land" and kind[int(right)] == "land":
            union(int(left), int(right))
    with PORTS_OUT.open("r", encoding="utf-8-sig", newline="") as handle:
        port_locations = {
            row["LandProvince"]
            for row in csv.DictReader(handle, delimiter=";")
        }
    port_components = {
        find(state.model.by_key[key].index)
        for key in port_locations
    }
    no_port_land = [
        location.key
        for location in state.model.locations
        if location.kind == "land"
        and find(location.index) not in port_components
    ]
    if no_port_land:
        sample = ", ".join(no_port_land[:20])
        failures.append(
            f"{len(no_port_land)} passable locations have no reachable port component: "
            f"{sample}"
        )
    for realm in realms:
        capital = state.ref_to_location[realm.capital_ref]
        capital_component = find(state.model.by_key[capital].index)
        if capital_component not in port_components:
            failures.append(
                f"{realm.tag} capital {capital} has no reachable port component"
            )
    missing = {
        location.key
        for location in state.model.locations
        if location.key not in state.ownership
    }
    if missing:
        failures.append(f"ownership ledger omits {len(missing)} locations")
    owned_non_land = [
        location.key
        for location in state.model.locations
        if location.kind != "land" and state.ownership[location.key] != WILD
    ]
    if owned_non_land:
        failures.append(
            f"{len(owned_non_land)} non-land locations have political owners"
        )
    bad_land = [
        location.key
        for location in state.model.locations
        if location.kind == "land"
        and state.ownership[location.key] == WILD
        and location.key not in state.wild_reason
    ]
    if bad_land:
        failures.append(f"{len(bad_land)} wild land locations lack a reason")
    pops = (ROOT / "main_menu/setup/start/06_pops.txt").read_text(
        encoding="utf-8-sig"
    )
    populated_ruins = [
        key
        for key, rank in state.rank.items()
        if rank == "ruin" and re.search(rf"(?m)^\s*{re.escape(key)}\s*=\s*\{{", pops)
    ]
    if populated_ruins:
        failures.append(f"canonical ruins retain census pops: {populated_ruins[:5]}")
    if len(state.names) != len(state.model.locations):
        failures.append("gazetteer does not cover every location")
    if len(set(state.names.values())) != len(state.names):
        failures.append("gazetteer display names are not unique")
    engineering = [
        name
        for name in state.names.values()
        if re.fullmatch(r"(?:Land|Sea|Lake|Mountain) \d+", name)
    ]
    if engineering:
        failures.append("engineering fill display names remain")
    banned = re.compile(
        r"\b(?:colonial|colony|crusade|pope|papal|catholic|protestant|"
        r"gunpowder|musket|cannon|renaissance|parliament|senate|republic|"
        r"Europe|Asia|Africa|America|French|Roman|Byzantine)\b",
        re.IGNORECASE,
    )
    visible = list(state.names.values()) + [
        value
        for realm in realms
        for value in (realm.name, realm.adjective)
    ]
    hits = [value for value in visible if banned.search(value)]
    if hits:
        failures.append(f"banned visible terms in M3 data: {hits[:5]}")
    game_dir = Path(
        json.loads(
            (ROOT / "config/local_paths.json").read_text(encoding="utf-8-sig")
        )["game_dir"]
    )
    emblem_dir = game_dir / "game/main_menu/gfx/coat_of_arms/colored_emblems"
    for realm in realms:
        if not (emblem_dir / realm.emblem).is_file():
            failures.append(f"{realm.tag} missing vanilla COA emblem {realm.emblem}")
    for path, expected in expected_payloads().items():
        if not path.is_file():
            failures.append(f"missing {path.relative_to(ROOT)}")
        elif path.read_text(encoding="utf-8") != expected:
            failures.append(f"{path.relative_to(ROOT)} differs from M3 model")
    for path, expected in expected_binary_payloads().items():
        if not path.is_file():
            failures.append(f"missing {path.relative_to(ROOT)}")
        elif path.read_bytes() != expected:
            failures.append(f"{path.relative_to(ROOT)} differs from M3 model")
    return failures


def main() -> int:
    parser = argparse.ArgumentParser()
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if args.write:
        write()
        return 0
    failures = check()
    if failures:
        for failure in failures:
            print(f"m3_realms: FAIL {failure}")
        return 1
    state = build_state()
    print(
        f"m3_realms: PASS ({len(state.realms)} realms, "
        f"{sum(value != WILD for value in state.ownership.values())} assigned, "
        f"{sum(value == WILD for value in state.ownership.values())} wild)"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
